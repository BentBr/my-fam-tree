//! The dependency matrix data.

/// Dependency rule for one workspace crate. Names are package names.
#[derive(Debug, Clone, Copy)]
pub struct Rule {
    pub krate: &'static str,
    /// Workspace crates this crate may depend on.
    pub allowed_internal: &'static [&'static str],
    /// External crates this crate must not depend on.
    pub forbidden_external: &'static [&'static str],
    /// Forbidden externals that are fine when the dependency is optional.
    pub optional_ok: &'static [&'static str],
    /// `(dependency, reason)` pairs allowed despite `forbidden_external`.
    pub exceptions: &'static [(&'static str, &'static str)],
}

